    public void setKolomTabel() {
        // mengatur lebar kolom untuk masing-masing kolom
        TableColumn column = null;
        for (int i = 0; i < 5; i++) {
            column = tabelMahasiswa.getColumnModel().getColumn(i);
            switch (i) {
                case 0:
                    column.setPreferredWidth(60);
                    break;
                case 1:
                    column.setPreferredWidth(100);
                    break;
                case 2:
                    column.setPreferredWidth(100);
                    break;
                case 3:
                    column.setPreferredWidth(80);
                    break;
                case 4:
                    column.setPreferredWidth(20);
                    break;
            }
        }
    }
    
    public void tampilData() {
        // melakukan koneksi ke database dan tabel via KoneksiDB
        try {
            Connection c = KoneksiDB.getKoneksi();
            Statement s = c.createStatement();
            String sql = "SELECT * FROM tbMahasiswa";
            ResultSet rs = s.executeQuery(sql);

            while (rs.next()) {
                // lakukan penelusuran baris
                Object[] o = new Object[5];
                o[0] = rs.getString("nim");
                o[1] = rs.getString("nama");
                o[2] = rs.getString("tmpLahir");
                o[3] = rs.getString("tglLahir");
                o[4] = rs.getString("jurusan");

                model.addRow(Arrays.asList(o));
            }
        } catch (SQLException e) {
            System.out.println("Terjadi error menampilkan data di tabel!");
        }
    }

    private java.sql.Date konversiDate(java.util.Date utilDate) {
        java.sql.Date sqlDate = null;
        if (utilDate != null) {
            sqlDate = new java.sql.Date(utilDate.getTime());
        }
        return sqlDate;
    }

