    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String nim = txtNIM.getText();
String nama = txtNama.getText();
SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

// jika tanggal lahir belum dipilih maka return
if (calTglLahir.getDate() == null) {
    return;
}

String tglLahir = sdf.format(calTglLahir.getDate());
String tmpLahir = txtTmpLahir.getText();
String jurusan = cboJurusan.getSelectedItem().toString();

// memasukkan data yang diinputkan ke database
try {
    Connection c = KoneksiDB.getKoneksi();
    String sql = "INSERT INTO tbMahasiswa VALUES (?, ?, ?, ?, ?)";
    PreparedStatement p = c.prepareStatement(sql);

    p.setString(1, nim);
    p.setString(2, nama);
    p.setString(3, tmpLahir);
    p.setDate(4, konversiDate(calTglLahir.getDate()));
    p.setString(5, jurusan);

    p.executeUpdate();
    p.close();

} catch (SQLException e) {
    System.out.println("Terjadi error menambah data di database");
}

// memasukkan data yang diinputkan ke dalam model
model.addRow(Arrays.asList(nim, nama, tmpLahir, tglLahir, jurusan));

// perbaharui tampilan jtable
tabelMahasiswa.setModel(model);

// mengatur kolom tabel
setKolomTabel();
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
 // TODO add your handling code here:

    // mengambil index dari baris yang dipilih/diseleksi
    int index = tabelMahasiswa.getSelectedRow();

    // jika tidak ada baris terseleksi maka return
    if (index == -1) {
        return;
    }

    // mengambil nilai-nilai isian pada form
    // nim, nama, tmplahir, tgllahir, jurusan
    String nim = txtNIM.getText();
    String nama = txtNama.getText();
    String tmpLahir = txtTmpLahir.getText();

    // jika date chooser belum diisi maka return
    if (calTglLahir.getDate() == null) {
        return;
    }

    SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
    String tglLahir = sdf.format(calTglLahir.getDate());
    String jurusan = cboJurusan.getSelectedItem().toString();

    // memasukkan data yang diedit ke dalam database
    try {
        Connection c = KoneksiDB.getKoneksi();
        String sql = "UPDATE tbMahasiswa SET nama=?, tmpLahir=?, tglLahir=?, jurusan=? WHERE nim=?"; // Corrected SQL query
        PreparedStatement p = c.prepareStatement(sql);
        p.setString(1, nama);
        p.setString(2, tmpLahir);
        p.setDate(3, konversiDate(calTglLahir.getDate()));
        p.setString(4, jurusan);
        p.setString(5, nim); // Corrected parameter index to 5

        p.executeUpdate();
        p.close();

    } catch (SQLException e) {
        System.out.println("Terjadi error mengubah data dalam database!");
    } finally {
        // memasukkan data yang diedit ke dalam model
        model.setValueAt(nim, index, 0);
        model.setValueAt(nama, index, 1);
        model.setValueAt(tmpLahir, index, 2);
        model.setValueAt(tglLahir, index, 3);
        model.setValueAt(jurusan, index, 4);

        // perbaharui tampilan jtable
        tabelMahasiswa.setModel(model);

        // mengatur kolom tabel
        setKolomTabel();

    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
int index = tabelMahasiswa.getSelectedRow();

// jika tidak ada baris terseleksi maka return
if (index == -1) {
    return;
}

// ambil yang terseleksi
String nim = (String) model.getValueAt(index, 0);

// menghapus data di database
try {
    Connection c = KoneksiDB.getKoneksi();
    String sql = "DELETE FROM tbMahasiswa WHERE nim = ?";
    PreparedStatement p = c.prepareStatement(sql);

    p.setString(1, nim);

    p.executeUpdate();
    p.close();

} catch (SQLException e) {
    System.out.println("Terjadi Error menghapus data!");

} finally {
    // menghapus baris di model tabel
    model.removeRow(index);
    // perbaharui tampilan jtable
    tabelMahasiswa.setModel(model);
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton3ActionPerformed

    private void tabelMahasiswaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelMahasiswaMouseClicked
        // TODO add your handling code here:
        int index = tabelMahasiswa.getSelectedRow();

// jika tidak ada baris terseleksi maka return
if (index == -1) {
    return;
}

// membuat variable (nim, nama, tmpLahir, tglLahir, jurusan) untuk
// menampung data berdasarkan baris yang dipilih/diseleksi
String nim = (String) tabelMahasiswa.getValueAt(index, 0);
String nama = (String) tabelMahasiswa.getValueAt(index, 1);
String tmpLahir = (String) tabelMahasiswa.getValueAt(index, 2);
String tglLahir = (String) tabelMahasiswa.getValueAt(index, 3);
String jurusan = (String) tabelMahasiswa.getValueAt(index, 4);

// menampilkan variabel-variabel yang dipilih ke text field
txtNIM.setText(nim);
txtNama.setText(nama);
txtTmpLahir.setText(tmpLahir);

// jika tanggal lahir kosong maka return
if (tglLahir.isEmpty()) {
    return;
}

// menampilkan variabel tglLahir ke calTglLahir
try {
    java.util.Date tanggal = new SimpleDateFormat("yyyy-MM-dd").parse(tglLahir);
    calTglLahir.setDate(tanggal);
} catch (Exception e) {
    System.out.println("Terjadi error menampilkan tanggal");
}

// menampilkan variabel-variable yang dipilih ke combo box
if (jurusan.equals("SI")) {
    cboJurusan.setSelectedIndex(0);
} else {
    cboJurusan.setSelectedIndex(1);
}
    }//GEN-LAST:event_tabelMahasiswaMouseClicked

