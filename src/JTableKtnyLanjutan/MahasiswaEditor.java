private void kosongkanIsian() {
    // menghapus isian dan mengatur seleksi ke default
    txtNama.setText("");
    cboJurusan.setSelectedIndex(0);
    calTglLahir.setCalendar(null);
    txtTmpLahir.setText("");
    cboJenisKelamin.setSelectedIndex(0);
}

public void setKolomTabel() {
    // mengatur lebar kolom untuk masing-masing kolom
    TableColumn column = null;
    for (int i = 0; i < 5; i++) { // Corrected loop condition to i < 5
        column = mhsView.getTabelMahasiswa().getColumnModel().getColumn(i);
        switch (i) {
            case 0:
                column.setPreferredWidth(80);
                break;
            case 1:
                column.setPreferredWidth(100);
                break;
            case 2:
                column.setPreferredWidth(50);
                break;
            case 3:
                column.setPreferredWidth(80);
                break;
            case 4:
                column.setPreferredWidth(20);
                break;
        }
    }
}

