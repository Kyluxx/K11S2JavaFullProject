    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
String nama = txtNama.getText();
String jurusan = cboJurusan.getSelectedItem().toString();
SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");

// jika tanggal lahir belum dipilih maka return
if (calTglLahir.getDate() == null) {
    return;
}

String tglLahir = sdf.format(calTglLahir.getDate());
String tmpLahir = txtTmpLahir.getText();
String jenisKelamin = cboJenisKelamin.getSelectedItem().toString();

// memasukkan data yang diinputkan ke dalam model
mhsView.getTabelModel().addRow(Arrays.asList(nama, jurusan,
        tglLahir, tmpLahir, jenisKelamin));

// perbaharui tampilan jtable
mhsView.getTabelMahasiswa().setModel(mhsView.getTabelModel());

// mengatur kolom tabel
setKolomTabel();

// kembali ke form MahasiswaView
dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
String nama = txtNama.getText();
String jurusan = cboJurusan.getSelectedItem().toString();
SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");
String tglLahir = sdf.format(calTglLahir.getDate());
String tmpLahir = txtTmpLahir.getText();
String jenisKelamin = cboJenisKelamin.getSelectedItem().toString();

// mengambil index dari baris yang dipilih/diseleksi
int index = mhsView.getTabelMahasiswa().getSelectedRow();

// jika tidak ada baris terseleksi maka return
if (index == -1) {
    return;
} else {
    // memasukkan data yang diedit ke dalam model
    mhsView.getTabelModel().setValueAt(nama, index, 0);
    mhsView.getTabelModel().setValueAt(jurusan, index, 1);
    mhsView.getTabelModel().setValueAt(tglLahir, index, 2);
    mhsView.getTabelModel().setValueAt(tmpLahir, index, 3);
    mhsView.getTabelModel().setValueAt(jenisKelamin, index, 4);
}

// perbaharui tampilan jtable
mhsView.getTabelMahasiswa().setModel(mhsView.getTabelModel());

// mengatur kolom tabel
setKolomTabel();

dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_btnUbahActionPerformed

