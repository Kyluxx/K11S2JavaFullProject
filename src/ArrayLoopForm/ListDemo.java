    private void hitungBiaya() {
        String value;
        ukuran = list2.getSize();
        if (ukuran < 0) {
            return;
        }
        total = 0;
        for (int i = 0; i < ukuran; i++) {
            value = list2.getElementAt(i).toString();
            if (value.equals("Paha Ayam")) {
                harga = 15000;
            } else if (value.equals("Dada Ayam")) {
                harga = 17000;
            } else if (value.equals("Cola")) {
                harga = 8000;
            } else if (value.equals("Milo")) {
                harga = 7500;
            } else if (value.equals("Kentang Goreng")) {
                harga = 12000;
            } else if (value.equals("Sup Ayam")) {
                harga = 5000;
            } else if (value.equals("Perkedel")) {
                harga = 5000;
            } else if (value.equals("Nasi Putih")) {
                harga = 5000;
            } else {
                harga = 0;
            }
            total = total + harga;
        }
        DecimalFormat df = new DecimalFormat("#,###");
        jTextField1.setText("Rp. " + df.format(total));
    }

