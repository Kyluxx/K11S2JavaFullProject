    private void jList1ValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jList1ValueChanged
        // TODO add your handling code here:
        int indeks;
        String value;

        indeks = jList1.getSelectedIndex();

        if (indeks < 0) {
            jLabel1.setText("Item belum dipilih!");
            return;
        }

        value = list1.getElementAt(indeks).toString();

        if (value.equals("Paha Ayam")) {
            harga = 15000;
        } else if (value.equals("Dada Ayam")) {
            harga = 17000;
        } else if (value.equals("Cola")) {
            harga = 8000;
        } else if (value.equals("Milo")) {
            harga = 7500;
        } else if (value.equals("Kentang Goreng")) {
            harga = 12000;
        } else if (value.equals("Sup Ayam")) {
            harga = 5000;
        } else if (value.equals("Perkedel")) {
            harga = 5000;
        } else if (value.equals("Nasi Putih")) {
            harga = 5000;
        } else {
            harga = 0;
        }

        DecimalFormat df = new DecimalFormat("#,###");
        jLabel1.setText(value + ": Rp. " + df.format(harga));
    }//GEN-LAST:event_jList1ValueChanged

