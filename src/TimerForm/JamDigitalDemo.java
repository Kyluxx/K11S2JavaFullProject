    public void setJamDigital() {
        Date tanggal = new Date();
        String formatWaktu = "HH:mm:ss a";
        SimpleDateFormat sdf = new SimpleDateFormat(formatWaktu);
        jLabel1.setText(sdf.format(tanggal));
        jLabel1.setFont(new Font("Arial", Font.BOLD, 40));
        jLabel1.setForeground(Color.YELLOW);
        jLabel1.setSize(100, 70);
    }

    public void start() {
        timer.start();
    }

    public void stop() {
        timer.stop();
    }

