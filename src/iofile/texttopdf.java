    public void saPDF(){
        if (b != null){
            try{
                OutputStream f = new FileOutputStream(b);
                
                Document d = new Document();
                PdfWriter.getInstance(d, f);
                
                d.open();
                try{
                    d.add(new Paragraph(jTextArea1.getText()));
                }catch(Exception e){}
                
                d.close();
                f.close();
            }catch(Exception e){}
        }
    }
