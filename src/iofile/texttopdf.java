    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        fc.setFileSelectionMode(JFileChooser.FILES_ONLY);
        
        FileNameExtensionFilter fl = new FileNameExtensionFilter("Text Document (*.txt, *.log)", "txt", "log");
        
        fc.setFileFilter(fl);
        fc.setMultiSelectionEnabled(false);
        
        int i = fc.showOpenDialog(this);
        
        if (i == fc.CANCEL_OPTION) return;
        
        File b = fc.getSelectedFile();
        
        if(b == null || b.getName().equals("")) return;
        
        try{
            BufferedReader bf = new BufferedReader(new FileReader(b));
            StringBuffer sb = new StringBuffer();
            
            String l;
            
            while((l = bf.readLine()) != null){
                sb.append(l + '\n');
            }
            jTextArea1.setText(sb.toString());
        }catch(Exception e){}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        JFileChooser jf = new JFileChooser(".");
        
        FileNameExtensionFilter f = new FileNameExtensionFilter("Portable Document Format (*.pdf)", "pdf");
        jf.setFileFilter(f);
        jf.setMultiSelectionEnabled(false);
        
        int i = jf.showSaveDialog(this);
        if (i == JFileChooser.APPROVE_OPTION){
            b = new File(jf.getSelectedFile().getPath() + ".pdf");
            saPDF();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

